//! The seven tables behind [`crate::words`]. One struct, so a phrase missing
//! from a language is a compile error rather than a blank menu line.

use crate::words::Counted;

pub struct Words {
    pub no_teams: &'static str,
    pub working: Counted,
    pub connecting: &'static str,
    pub paused: &'static str,
    pub not_connected: &'static str,
    pub service_unreachable: &'static str,
    pub requests: Counted,
    pub owner_confirmation: &'static str,
    pub failure: &'static str,
    pub documents: &'static str,
    pub pause: &'static str,
    pub resume: &'static str,
    pub all_teams: &'static str,
    pub open_window: &'static str,
    pub open_nessie: &'static str,
    pub quit: &'static str,
    pub team_unavailable: &'static str,
    pub request_title_agent: &'static str,
    pub request_title: &'static str,
    pub request_team: &'static str,
    pub allow_once: &'static str,
    pub always_allow: &'static str,
    pub dont_allow: &'static str,
    pub pause_failed: &'static str,
    pub resume_failed: &'static str,
    pub open_nessie_failed: &'static str,
    pub answer_failed: &'static str,
}

