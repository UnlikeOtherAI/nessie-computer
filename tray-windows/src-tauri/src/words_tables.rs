//! The seven tables behind [`crate::words`]. One struct, so a phrase missing
//! from a language is a compile error rather than a blank menu line. The
//! menu's sentences are the macOS menu bar's (`menubar-macos/Sources/Core/
//! Words+*.swift`), with "this Mac" read as "this computer": the contract asks
//! for identical items on both.

use crate::words::Counted;

