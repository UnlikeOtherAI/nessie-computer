// Generates only thin method/codec relations. Original schemas are dependencies.
import { readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { WsRpcGroup, EnvironmentHttpApi, OrchestrationV2Command, AssetResource, ProjectMutation } from '@nessie/t3-session-source/contracts'
import { isStreamSchema } from 'effect/rpc/RpcSchema'
import rawHttp from '@nessie/t3-session-source/routes' with { type: 'json' }
import commandInventory from '@nessie/t3-session-source/command-inventory' with { type: 'json' }
import sourceProvenance from '@nessie/t3-session-source/provenance' with { type: 'json' }
import { ServerSettingsPatch } from '@nessie/t3-session-source/contracts/settings'

const directory = dirname(fileURLToPath(import.meta.url))
const ledger = JSON.parse(readFileSync(resolve(directory, 'ledger.json'), 'utf8'))
const inventoryBytes = readFileSync(new URL(import.meta.resolve('@nessie/t3-session-source/command-inventory')))
if (commandInventory.format !== 1 || commandInventory.source !== 'packages/contracts/src/orchestrationV2.ts'
  || commandInventory.sourceSha256 !== sourceProvenance.files.find(file => file.path === commandInventory.source)?.sha256
  || createHash('sha256').update(inventoryBytes).digest('hex') !== sourceProvenance.commandInventorySha256
  || !Array.isArray(commandInventory.internalCommands)
  || commandInventory.internalCommands.some(command => typeof command !== 'string')
  || new Set(commandInventory.internalCommands).size !== commandInventory.internalCommands.length) {
  throw Error('T3_COMMAND_INVENTORY_IDENTITY_MISMATCH')
}
const commands = [...OrchestrationV2Command.members.map(x => x.fields.type.literal),
  ...ProjectMutation.members.map(x => x.fields.type.literal),
  ...commandInventory.internalCommands]
const inventories = {
  rpc: [...WsRpcGroup.requests.keys()],
  http: Object.entries(EnvironmentHttpApi.groups).flatMap(([group, value]) => Object.keys(value.endpoints).map(key => `${group}.${key}`)),
  commands,
  resources: AssetResource.members.map(value => value.fields._tag.ast.literal),
  rawHttp: rawHttp.map(route => route.id),
  settingsFields: Object.keys(ServerSettingsPatch.fields),
}
for (const route of rawHttp) if (ledger.rawHttp[route.id].sourceSha256 !== route.sourceSha256
  || ledger.rawHttp[route.id].pathExpression !== route.pathExpression) throw Error('T3_RAW_HTTP_SOURCE_CHANGED')
for (const [kind, names] of Object.entries(inventories)) {
  if (JSON.stringify([...names].sort()) !== JSON.stringify(Object.keys(ledger[kind]).sort())) {
    throw Error(`T3_UNCLASSIFIED_SOURCE_${kind.toUpperCase()}`)
  }
}
const selected = [...WsRpcGroup.requests.values()].filter(rpc => ledger.rpc[rpc._tag].status === 'pending'
  && ledger.rpc[rpc._tag].sensitivity !== 'sealed-session-answer')
const literal = value => JSON.stringify(value)
const methods = `// Generated by generate.mjs from original WsRpcGroup descriptors; do not edit.
import { originalRpc, type OriginalRpc } from './descriptors.js'
export type ExecutorT3Method = ${selected.map(rpc => literal(rpc._tag)).join(' | ')}
export type ExecutorT3Descriptor<M extends ExecutorT3Method> = Extract<OriginalRpc, { readonly _tag: M }>
export const ExecutorT3Descriptors: { readonly [M in ExecutorT3Method]: ExecutorT3Descriptor<M> } = {
${selected.map(rpc => `  ${literal(rpc._tag)}: originalRpc(${literal(rpc._tag)}),`).join('\n')}
}
`
const request = `// Generated method-correlated original codec union; do not edit.
import * as Schema from 'effect/Schema'
import { ExecutorT3Routing } from './routing.js'
import { CommandId } from '@nessie/t3-session-source/contracts'
import { ExecutorT3Descriptors as D, type ExecutorT3Method, type ExecutorT3Descriptor } from './methods.js'
import { ClientCommand } from './commands.js'
import { isAdmissibleT3Request } from './validation.js'
type Input<M extends ExecutorT3Method> = ExecutorT3Descriptor<M>['payloadSchema']
export type ExecutorT3Request = { [M in ExecutorT3Method]: ExecutorT3Routing & {
  readonly kind: 'request'; readonly method: M; readonly input: Input<M>['Type']; readonly commandId?: typeof CommandId.Type
} }[ExecutorT3Method]
export type ExecutorT3RequestEncoded = { [M in ExecutorT3Method]: typeof ExecutorT3Routing.Encoded & {
  readonly kind: 'request'; readonly method: M; readonly input: Input<M>['Encoded']; readonly commandId?: typeof CommandId.Encoded
} }[ExecutorT3Method]
export const ExecutorT3Request: Schema.Codec<ExecutorT3Request, ExecutorT3RequestEncoded> = Schema.Union([
${selected.map(rpc => `  Schema.Struct({ ...ExecutorT3Routing.fields, kind: Schema.Literal('request'), commandId: Schema.optionalKey(CommandId), method: Schema.Literal(${literal(rpc._tag)}), input: ${rpc._tag === 'orchestration.dispatchCommand' ? 'ClientCommand' : `D[${literal(rpc._tag)}].payloadSchema`} }),`).join('\n')}
]).check(Schema.makeFilter(isAdmissibleT3Request))
`
const reply = `// Generated result/error/stream relations; do not edit.
import * as Schema from 'effect/Schema'
import type * as RpcSchema from 'effect/rpc/RpcSchema'
import { ExecutorT3Routing } from './routing.js'
import { ExecutorT3Descriptors as D, type ExecutorT3Method, type ExecutorT3Descriptor } from './methods.js'
type Success<M extends ExecutorT3Method> = ExecutorT3Descriptor<M>['successSchema']
type Value<M extends ExecutorT3Method> = Success<M> extends RpcSchema.Stream<infer A, infer _E> ? A : Success<M>
type Failure<M extends ExecutorT3Method> = ExecutorT3Descriptor<M>['errorSchema'] |
  (Success<M> extends RpcSchema.Stream<infer _A, infer E> ? E : never)
type Kind<M extends ExecutorT3Method> = Success<M> extends RpcSchema.Stream<infer _A, infer _E> ? 'stream' : 'result'
export type ExecutorT3Result = { [M in ExecutorT3Method]: ExecutorT3Routing & {
  readonly kind: Kind<M>; readonly method: M; readonly result: Value<M>['Type']
} }[ExecutorT3Method]
export type ExecutorT3ResultEncoded = { [M in ExecutorT3Method]: typeof ExecutorT3Routing.Encoded & {
  readonly kind: Kind<M>; readonly method: M; readonly result: Value<M>['Encoded']
} }[ExecutorT3Method]
export type ExecutorT3Error = { [M in ExecutorT3Method]: ExecutorT3Routing & {
  readonly kind: 'error'; readonly method: M; readonly error: Failure<M>['Type']
} }[ExecutorT3Method]
export type ExecutorT3ErrorEncoded = { [M in ExecutorT3Method]: typeof ExecutorT3Routing.Encoded & {
  readonly kind: 'error'; readonly method: M; readonly error: Failure<M>['Encoded']
} }[ExecutorT3Method]
export const ExecutorT3Result: Schema.Codec<ExecutorT3Result, ExecutorT3ResultEncoded> = Schema.Union([
${selected.map(rpc => `  Schema.Struct({ ...ExecutorT3Routing.fields, kind: Schema.Literal('${isStreamSchema(rpc.successSchema) ? 'stream' : 'result'}'), method: Schema.Literal(${literal(rpc._tag)}), result: D[${literal(rpc._tag)}].successSchema${isStreamSchema(rpc.successSchema) ? '.success' : ''} }),`).join('\n')}
])
export const ExecutorT3Error: Schema.Codec<ExecutorT3Error, ExecutorT3ErrorEncoded> = Schema.Union([
${selected.map(rpc => `  Schema.Struct({ ...ExecutorT3Routing.fields, kind: Schema.Literal('error'), method: Schema.Literal(${literal(rpc._tag)}), error: ${isStreamSchema(rpc.successSchema) ? `Schema.Union([D[${literal(rpc._tag)}].errorSchema, D[${literal(rpc._tag)}].successSchema.error])` : `D[${literal(rpc._tag)}].errorSchema`} }),`).join('\n')}
])
`
for (const [name, content] of Object.entries({ 'methods.ts': methods, 'request.ts': request, 'reply.ts': reply })) {
  if (process.argv.includes('--write')) writeFileSync(resolve(directory, name), content)
  else if (readFileSync(resolve(directory, name), 'utf8') !== content) throw Error(`T3_GENERATED_RELATION_STALE:${name}`)
}
process.stdout.write(`T3 classified ${inventories.rpc.length} RPC / ${inventories.http.length} HTTP / ${rawHttp.length} raw routes / ${commands.length} commands / ${inventories.resources.length} resources; ${selected.length} ordinary transport descriptors\n`)
