import { requireCodex } from './identity.js'

export type CodexRolloutRecord = {
  readonly timestamp?: string; readonly type: string; readonly payload: Record<string, unknown>
}
export const codexRecord = (value: unknown): Record<string, unknown> | undefined =>
  value !== null && typeof value === 'object' && !Array.isArray(value) ? value as Record<string, unknown> : undefined

/** Parse only held rollout bytes. A malformed record never silently disappears from complete history. */
export function parseCodexRolloutLine(line: string): CodexRolloutRecord {
  requireCodex(Buffer.byteLength(line) <= 1024 * 1024, 'codex_record_too_large')
  let value: unknown
  try { value = JSON.parse(line) } catch { requireCodex(false, 'codex_record_invalid_json') }
  const row = codexRecord(value)
  requireCodex(row && typeof row.type === 'string' && codexRecord(row.payload) &&
    (row.timestamp === undefined || typeof row.timestamp === 'string'), 'codex_record_unsupported')
  return row as CodexRolloutRecord
}

const fields = (row: Record<string, unknown>, names: readonly string[]): Record<string, unknown> =>
  Object.fromEntries(names.filter(name => Object.hasOwn(row, name)).map(name => [name, row[name]]))

const responseFields: Readonly<Record<string, readonly string[]>> = Object.freeze({
  message: ['type', 'id', 'role', 'content', 'phase', 'end_turn'],
  reasoning: ['type', 'id', 'summary'], // Never encrypted_content or private chain-of-thought.
  function_call: ['type', 'id', 'call_id', 'name', 'arguments', 'status'],
  custom_tool_call: ['type', 'id', 'call_id', 'name', 'input', 'status'],
  function_call_output: ['type', 'id', 'call_id', 'output'],
  custom_tool_call_output: ['type', 'id', 'call_id', 'output'],
  web_search_call: ['type', 'id', 'status', 'action'],
  local_shell_call: ['type', 'id', 'call_id', 'status', 'action'],
  image_generation_call: ['type', 'id', 'status'], // Generated bytes need the admitted resource lane.
})
const eventFields: Readonly<Record<string, readonly string[]>> = Object.freeze({
  user_message: ['type', 'message', 'images', 'local_images', 'text_elements'],
  agent_message: ['type', 'message', 'phase'],
  agent_reasoning: ['type', 'text'],
  task_started: ['type', 'turn_id'],
  task_complete: ['type', 'turn_id', 'last_agent_message'],
  turn_aborted: ['type', 'turn_id', 'reason'],
  context_compacted: ['type'],
  thread_rolled_back: ['type', 'num_turns'],
})

/** Native record shape/order is retained, not flattened into the recent-message DTO.
 * Unsupported variants remain an explicit slot; excluded metrics have no display payload.
 */
export function projectCodexRecord(record: CodexRolloutRecord): {
  readonly record: CodexRolloutRecord | null
  readonly omission: 'excluded' | 'unsupported' | null
} {
  const payload = record.payload
  const type = typeof payload.type === 'string' ? payload.type : ''
  if (record.type === 'event_msg' && type === 'token_count') return { record: null, omission: 'excluded' }
  let selected: readonly string[] | undefined
  if (record.type === 'session_meta') selected = ['id', 'timestamp', 'forked_from_id', 'source', 'originator', 'cli_version']
  else if (record.type === 'response_item') selected = responseFields[type]
  else if (record.type === 'event_msg') selected = eventFields[type]
  else if (record.type === 'compacted') selected = ['message']
  else if (record.type === 'turn_context') selected = ['turn_id', 'model']
  if (!selected) return { record: null, omission: 'unsupported' }
  return { record: { ...(record.timestamp === undefined ? {} : { timestamp: record.timestamp }),
    type: record.type, payload: fields(payload, selected) },
  omission: record.type === 'response_item' && type === 'image_generation_call' ? 'unsupported' : null }
}
