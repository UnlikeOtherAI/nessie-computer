import assert from 'node:assert/strict'
import test from 'node:test'

import { createMatrix, type Computer } from './support/folder-sync-sim/matrix-world.js'

/** The resolution rules R1–R7 (plan §3), each through the whole engine. */

const reasons = (computer: Computer) => computer.openRows().map((row) => row.reason)

test('R1 read-only wins: something new in a space this person cannot write stays here, is never sent, and a row says so', async (t) => {
  const w = await createMatrix()
  t.after(w.cleanup)
  const locked = w.server.actor.space('Handbook', { writable: false })
  w.server.actor.create({ spaceId: locked.id, parentPageId: null, kind: 'document', title: 'Rules', content: 'r\n' })
  await w.start()
  await w.pc.write('Handbook/my notes.txt', 'mine')
  await w.pc.settle()
  assert.equal(w.server.livePages().length, 1)
  assert.equal(await w.pc.read('Handbook/my notes.txt'), 'mine')
  assert.deepEqual(reasons(w.pc), ['read_only_no_write_access'])
})

test('R2 the server is the arbiter: Nessie\'s head keeps the path and its history; ours is a named copy in both places', async (t) => {
  const w = await createMatrix()
  t.after(w.cleanup)
  const page = w.server.actor.create({ spaceId: w.space.id, parentPageId: null, kind: 'file', title: 'photo.png', content: 'v1' })
  await w.start()
  w.server.actor.edit(page.id, 'theirs')
  await w.pc.write('Projects/photo.png', 'mine')
  await w.pc.settle()
  await w.pc.settle()
  assert.deepEqual(page.versions.map((version) => Buffer.from(version.bytes).toString()), ['v1', 'theirs'])
  const [copy] = await w.pc.copies('Projects')
  assert.match(copy!, /^photo \(conflicted copy – Laptop – \d{4}-\d{2}-\d{2} \d{4}\)\.png$/u)
  assert.equal(w.text(`Projects/${copy}`), 'mine')
  const [row] = w.pc.openRows()
  assert.equal(row?.copy?.relPath, `Projects/${copy}`)
  assert.equal(row?.headVersionId, page.versions[1]!.versionId)
})

test('R3 a clean three-way merge of a text file is one new version; the pre-merge text is kept in the trash', async (t) => {
  const w = await createMatrix()
  t.after(w.cleanup)
  const page = w.server.actor.create({ spaceId: w.space.id, parentPageId: null, kind: 'file', title: 'todo.txt', content: 'a\nb\nc\n' })
  await w.start()
  w.server.actor.edit(page.id, 'A\nb\nc\n')
  await w.pc.write('Projects/todo.txt', 'a\nb\nC\n')
  await w.pc.settle()
  assert.equal(w.server.text(page), 'A\nb\nC\n')
  assert.equal(page.versions.length, 3)
  assert.equal(await w.pc.read('Projects/todo.txt'), 'A\nb\nC\n')
  assert.ok((await w.pc.trash()).some((entry) => entry.relPath === 'Projects/todo.txt'))
  assert.deepEqual(w.pc.rows(), [])
})

test('R4 an edit beats a delete across computers: one deletes, the other edits — the edit wins everywhere', async (t) => {
  const w = await createMatrix({ computers: 2 })
  t.after(w.cleanup)
  const [laptop, desktop] = w.computers as [Computer, Computer]
  const page = w.server.actor.create({ spaceId: w.space.id, parentPageId: null, kind: 'document', title: 'Keep', content: 'k\n' })
  await w.start()
  await desktop.write('Projects/Keep.md', 'k\nedited\n')
  await desktop.settle()
  await laptop.remove('Projects/Keep.md')
  await w.settleAll()
  assert.equal(page.status, 'live')
  assert.equal(await laptop.read('Projects/Keep.md'), 'k\nedited\n')
  assert.deepEqual(reasons(laptop), ['deleted_here_restored'])
})

test('R5 deletes are soft: a local delete archives without purging; a delete in Nessie goes to the trash and can be put back', async (t) => {
  const w = await createMatrix()
  t.after(w.cleanup)
  const mine = w.server.actor.create({ spaceId: w.space.id, parentPageId: null, kind: 'file', title: 'mine.txt', content: 'm' })
  const theirs = w.server.actor.create({ spaceId: w.space.id, parentPageId: null, kind: 'file', title: 'theirs.txt', content: 't' })
  await w.start()
  await w.pc.remove('Projects/mine.txt')
  w.server.actor.archive(theirs.id)
  await w.pc.settle()
  assert.equal(mine.status, 'archived')
  assert.equal(w.server.text(mine), 'm', 'the archived page keeps its bytes')
  assert.equal(await w.pc.readOrNull('Projects/theirs.txt'), null)
  const [entry] = (await w.pc.trash()).filter((item) => item.relPath === 'Projects/theirs.txt')
  assert.ok(entry)
  assert.equal((await w.pc.command({ command: 'restore_trash', entryId: entry.entryId } as never)).outcome, 'applied')
  await w.pc.settle()
  assert.equal(await w.pc.read('Projects/theirs.txt'), 't')
  assert.equal(w.text('Projects/theirs.txt'), 't', 'put back, it is a page again')
})

test('R6 names are structural: two computers rename one file differently — the first rename wins, the other follows and is told', async (t) => {
  const w = await createMatrix({ computers: 2 })
  t.after(w.cleanup)
  const [laptop, desktop] = w.computers as [Computer, Computer]
  const page = w.server.actor.create({ spaceId: w.space.id, parentPageId: null, kind: 'document', title: 'Draft', content: 'd\n' })
  await w.start()
  await laptop.rename('Projects/Draft.md', 'Projects/Laptop name.md')
  await desktop.rename('Projects/Draft.md', 'Projects/Desktop name.md')
  await laptop.settle()
  await w.settleAll()
  assert.equal(page.title, 'Laptop name')
  for (const computer of w.computers) assert.deepEqual(await computer.list('Projects'), ['Laptop name.md'])
  assert.deepEqual(reasons(desktop), ['renamed_in_nessie'])
  assert.deepEqual(reasons(laptop), [])
})

test('R7 everything is told once: one row per conflict, across passes, restarts and repeated reports', async (t) => {
  const w = await createMatrix()
  t.after(w.cleanup)
  const page = w.server.actor.create({ spaceId: w.space.id, parentPageId: null, kind: 'file', title: 'deck.bin', content: 'v1' })
  await w.start()
  w.server.actor.edit(page.id, 'theirs')
  await w.pc.write('Projects/deck.bin', 'mine')
  await w.pc.settle()
  w.pc.restart()
  await w.pc.settle()
  w.advance(11 * 60 * 1000)
  await w.pc.settle()
  assert.equal(w.pc.rows().length, 1)
  const reported = w.pc.view.reports.flatMap((report) => report.conflicts.map((row) => row.clientConflictId))
  assert.equal(new Set(reported).size, 1)
  assert.equal(reported.length, 1, 'the row was sent once')
  assert.equal((await w.pc.state()).conflicts.length, 1)
})
